local function hex(s)
    local t = {}
    for i = 1, #s do t[i] = string.format("%02x", string.byte(s, i)) end
    return table.concat(t)
end

local function unhex(h)
    local t = {}
    for i = 1, #h, 2 do t[#t + 1] = string.char(tonumber(string.sub(h, i, i + 1), 16)) end
    return table.concat(t)
end

local function check_bytes(name, addr, expected_hex)
    local got = memory.read(addr, #expected_hex / 2)
    local same = (got ~= nil and hex(got) == expected_hex)
    log(string.format("check: %-22s at %08x  %s", name, addr,
        same and "as expected" or ("DIFFERENT: " .. (got and hex(got) or "not readable"))))
    return same, got
end

function m.init(ctx)
    log("MLGrowth 5: a moderated age curve for every Master League player "
        .. "(potential and playtime decide growth, young players still lead, "
        .. "physical decline from 31, training follows the curve too)")

    -- 1. the code the cave jumps to and calls must be where it is
    local good = true
    for _, c in ipairs(CONTEXT) do
        if not check_bytes(c[1], c[2], c[3]) then good = false end
    end

    -- 2. the four hook sites
    for _, s in ipairs(SITES) do
        local ok, got = check_bytes(s[1], s[2], s[3])
        if not ok then
            local head = got ~= nil and string.sub(hex(got), 1, 2) or ""
            if head == "e9" or head == "e8" then
                log("RESULT: nothing written. A growth hook is already modified "
                    .. "(another module or MLGrowth.lua listed twice in sider.ini).")
                return
            end
            good = false
        end
    end

    -- 3. every cave must be zero
    for _, b in ipairs(BLOCKS) do
        local room = memory.read(b[2], #b[3] / 2)
        local empty = (room ~= nil and room == string.rep("\0", #b[3] / 2))
        log(string.format("check: %-22s at %08x  %s", b[1], b[2], empty and "empty" or "NOT EMPTY"))
        if not empty then good = false end
    end

    if not good then
        log("RESULT: nothing written. This game does not hold what the module expects; "
            .. "send this log.")
        return
    end

    -- 4. write the caves first (nothing jumps to them yet)
    for _, b in ipairs(BLOCKS) do
        local img = unhex(b[3])
        memory.write(b[2], img)
        if memory.read(b[2], #img) ~= img then
            log("RESULT: the " .. b[1] .. " could not be written; the game's code is "
                .. "unchanged. Send this log.")
            return
        end
    end

    -- 5. patch the four hook sites
    for i, s in ipairs(SITES) do
        local new = unhex(s[4])
        memory.write(s[2], new)
        local stuck = (memory.read(s[2], #new) == new)
        log(string.format("written: %-20s at %08x  %s", s[1], s[2], stuck and "ok" or "FAILED"))
        if not stuck then
            local restored = true
            for j = i, 1, -1 do
                local site = SITES[j]
                local old = unhex(site[3])
                memory.write(site[2], old)
                if memory.read(site[2], #old) ~= old then restored = false end
            end
            log("RESULT: a change did not go in. " .. (restored and "Hooks restored. " or "Hook restore failed. ")
                .. "Quit the game, remove the module, send this log.")
            return
        end
    end

    log("RESULT: installed. The moderated age curve is scaled by potential and "
        .. "playtime, the training focus follows it, and every other player gains a "
        .. "few position-specific points a season until the curve flattens.")
end

return m
