-- MLGrowth.lua, version 1: an age curve for every Master League player (Sider Lua
-- module). Made for PES2017.exe sha256 44b0caaa...
--
-- What the game does (MASTER_LEAGUE.md, section 12): Master League keeps growth
-- records (experience, carry, match counters, pending events) for about fifty players
-- only -- the user's squad and the youth team.  Experience is awarded through one
-- function, fcn_038b2fc4, whose amount is the same at every age: a 33-year-old grows
-- as fast as a 17-year-old, and declines hit every ability equally.  Every other
-- player of the game -- the AI majority, 19,871 of 19,921 in the test save -- has no
-- record, gets no experience at all and is frozen for his whole career.  Once a season
-- a walk over all players raises only their age.
--
-- What the module changes, in the running game only (no file is touched):
--   A. The exp award fcn_038b2fc4 now multiplies the exp by an age curve (x3.0 at 15
--      down to x0.25 from 30), by a potential scale (how close the player is to the
--      ceiling his age allows) and, for a player with a growth record, by his playtime
--      of the cycle.  Negative exp (the game's decline awards) is dampened to a
--      quarter, except the physical fields (speed, body balance, physical contact,
--      explosive power, jumping, stamina) from 31 on, which decline in full.  Guards,
--      carry, level-ups, news and the growth report run as before.
--   B. The season walk now also gives every player WITHOUT a growth record a few
--      points on the ability of his position (CF/SS finishing, DMF and defenders
--      defending, GK goalkeeping, the rest dribbling), following the same curve, so
--      young AI players develop and old ones stall.  Players with a record are left
--      to hook A.
--
-- It first checks that the game holds the expected code at every place it touches and
-- that its caves are zero.  If anything differs it writes nothing and says so in
-- sider.log.
--
-- Install: copy this file into the "modules" folder next to sider.exe and add
--     lua.module = "MLGrowth.lua"
-- to sider.ini, above or below the other lines.  Remove the line to get the vanilla
-- growth back; nothing of the game or of a save is edited on disk.
--
-- It needs no other module, and no other module needs it.  It does not overlap the
-- caves of MLSimMatch.lua, MLMoney.lua, MLTransfers.lua or MLSimToDate.lua.
--
-- Uses only: log, memory.read, memory.write, string, table, tonumber.

